/// Проверяет, что русское имя выглядит «сломанным» — содержит
/// больше одной запятой (мусорные данные mp3quran id=256, 259) или
/// имеет явно урезанные формы (например, «Мшари» без «и»).
bool looksLikeBrokenRussian(String s) {
  if (s.isEmpty) return true;
  if (s.split(',').length > 3) return true; // мусор: "Коран,Аудио,Библиотека,..."
  if (RegExp(r'Мшари\b').hasMatch(s)) return true; // пропала "и"
  if (s.length < 4) return true;
  return false;
}
