/// Распознавание басмалы в тексте аята.
///
/// В Mushaf-каноне басмала (`بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ`)
/// традиционно отображается **отдельно** от текста первой суры —
/// строкой-«шапкой» по центру страницы, после которой сура
/// начинается с новой строки. В данных `quran_full.json` (Alquran.cloud)
/// используются два варианта хранения басмалы:
///
/// 1. **Сура 1 (Аль-Фатиха)**: первый аят **полностью** совпадает
///    с басмалой, без дополнительного текста:
///    `بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ`. Весь этот аят
///    нужно вынести в отдельный заголовок, а сура начинается
///    со 2-го аята.
///
/// 2. **Суры 2–114 (кроме 9)**: первый аят **начинается** с басмалы,
///    за которой сразу идёт основной текст первого аята без пробела:
///    `بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ الم` (сура 2),
///    `بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ قُلْ هُوَ ٱللَّهُ أَحَدٌ` (сура 112).
///    Нужно **отделить** префикс-басмалу от остатка и показать
///    заголовком только басмалу, а остаток оставить в потоке.
///
/// 3. **Сура 9 (Ат-Тауба)**: басмалы нет вообще, первый аят
///    начинается с «بَرَآءَةٌۭ ...» (объявление о разрыве договоров).
///    Детектор должен вернуть `false` для таких аятов.
///
/// **Unicode-нормализация**: разные издания Корана используют
/// разные формы огласовок (харакат, шадда, татвиль) и алифа
/// (ٱ — алиф-васла U+0671, ا — обычный алиф). Внутри утилиты
/// **все диакритические знаки** удаляются, а алиф-васла
/// приводится к обычному алифу (см. [_normalize]). Это позволяет
/// детектору быть устойчивым к разным стилям начертания.
class Bismillah {
  Bismillah._();

  /// Эталонный текст басмалы (письмо Усмани, стиль Alquran.cloud,
  /// с алиф-васлой ٱ). Используется для рендера в book-mode
  /// во всех сурах (визуально единообразно).
  static const String standardText =
      'بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ';

  /// Нормализованный «корень» басмалы — только базовые буквы без
  /// диакритик, без алиф-васлы, без татвиля. Используется в
  /// [_startsWithBismillah] для устойчивого сравнения по корню.
  static String get _standardRoot => _normalizeRoot(standardText);

  /// Длина «корня» — фиксированное значение для всех сура-вариантов.
  static final int _rootLength = _standardRoot.runes.length;

  /// Является ли [text] басмалой.
  ///
  /// **Семантика**: возвращает `true`, если текст **начинается** с
  /// басмалы — независимо от того, является ли текст только басмалой
  /// (Аль-Фатиха) или басмалой + остатком первого аята (большинство
  /// сур). Этот метод нужен для определения «надо ли в book-mode
  /// вынести заголовок-басмалу».
  ///
  /// Сравнение идёт по **корню** (только базовые буквы), поэтому
  /// детектор устойчив к разным формам огласовок и алифа в исходных
  /// данных.
  ///
  /// Возвращает `true` для:
  /// - «بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ» (Аль-Фатиха)
  /// - «بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ» (вариант без татвиля)
  /// - «بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ الم» (Аль-Бакара)
  /// - «بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ قُلْ هُوَ ٱللَّهُ أَحَدٌ» (Аль-Ихлас)
  ///
  /// Возвращает `false` для:
  /// - «بَرَآءَةٌۭ مِّنَ ٱللَّهِ ...» (Ат-Тауба)
  /// - «ٱلْحَمْدُ لِلَّهِ رَبِّ ٱلْعَٰلَمِينَ» (2-й аят Аль-Фатиха)
  /// - пустой строки, не-арабского текста
  static bool isBismillah(String text) => _startsWithBismillah(text);

  /// Синоним [isBismillah] — для явного именования в коде.
  static bool containsBismillah(String text) => _startsWithBismillah(text);

/// Разделяет текст первого аята на басмалу и остаток.
  ///
  /// - Для суры 1 (только басмала): возвращает `(standardText, null)`.
  /// - Для остальных сур с басмалой + текст: возвращает
  ///   `(standardText, restAfterBismallah)`, где `restAfterBismallah`
  ///   — это часть аята **после** басмалы, **с сохранением всех
  ///   диакритик** (харакат, шадда, maddahan и т.д.).
  /// - Для суры 9 (нет басмалы): возвращает `(null, text)`.
  ///
  /// **Важно**: `rest` возвращается **с диакритиками**, не
  /// нормализованным. Для определения позиции отреза используется
  /// `_normalizeRoot` (только для сравнения длин), но сам
  /// возвращаемый текст — это **исходная** строка, начиная с
  /// позиции, соответствующей концу басмалы в нормализованной
  /// форме. Это критично для корректного отображения харакат в
  /// первом аяте (например, «ٱلۡحۡمۡدۡ» в Аль-Фатихе или
  /// «ٱلٓمٓۛ» в Аль-Бакаре).
  static ({String? basmala, String? rest}) split(String text) {
    if (!_startsWithBismillah(text)) {
      return (basmala: null, rest: text);
    }
    final trimmed = text.trim();
    final root = _normalizeRoot(trimmed);
    if (root.runes.length == _rootLength) {
      return (basmala: standardText, rest: null);
    }
// Нужно отрезать от **исходной** строки столько **исходных**
    // символов, сколько басмала занимает в нормализованной форме.
    // Так как 1 rune в нормализованной форме соответствует ровно
    // одному rune в исходной (диакритики не считаются в root),
    // мы итерируем по runes **исходной** строки и удаляем
    // **только непомеченные** rune'ы, пока не пройдём `_rootLength`
    // корневых символов. Так остаются все харакат/shadda/maddahan.
    var keptRootCount = 0;
    var cutIndex = 0;
    final runes = trimmed.runes.toList(growable: false);
    for (var i = 0; i < runes.length; i++) {
      if (_isArabicMark(runes[i])) continue; // пропускаем диакритики
      // Корень содержит ٱ → ا; в исходном тексте может быть ٱ.
      // Мы «считаем» ٱ как корень-символ (эквивалент ا в root).
      keptRootCount++;
      if (keptRootCount == _rootLength) {
        cutIndex = i + 1;
        break;
      }
    }
    if (cutIndex == 0 || cutIndex >= runes.length) {
      // Fallback: вся строка — только басмала (не должно
      // произойти, т.к. root.length > _rootLength → cutIndex > 0).
      return (basmala: standardText, rest: null);
    }
    // После 21-го корневого символа басмалы (последний — `م` в
    // «الرحيم») могут идти **диакритики**, принадлежащие этому
    // последнему символу (kasra `ِ` и т.д.). Они НЕ должны попасть
    // в `rest` — это часть басмалы, а не начало следующего аята.
    // Расширяем `cutIndex` вправо, пока идут диакритики.
    while (cutIndex < runes.length && _isArabicMark(runes[cutIndex])) {
      cutIndex++;
    }
    final restStr = String.fromCharCodes(runes.sublist(cutIndex));
    return (basmala: standardText, rest: restStr);
  }

  /// Текст басмалы для рендера в book-mode заголовке.
  static String? renderText(String? ayahText) {
    if (ayahText == null) return null;
    if (!_startsWithBismillah(ayahText)) return null;
    return standardText;
  }

  /// Проверяет, начинается ли [text] с басмалы.
  ///
  /// Сравнение идёт по «корню» (только базовые буквы без огласовок).
  /// Длина эталона фиксирована, и для суры 1 (только басмала)
  /// `root.length == _rootLength`. Для остальных сур с басмалой +
  /// остаток `root.length > _rootLength`. Для сур без басмалы
  /// первые буквы `бسم` не совпадут.
  static bool _startsWithBismillah(String text) {
    if (text.isEmpty) return false;
    final root = _normalizeRoot(text.trim());
    if (root.runes.length < _rootLength) return false;
    final textRunes = root.runes.toList(growable: false);
    final standardRunes = _standardRoot.runes.toList(growable: false);
    for (var i = 0; i < _rootLength; i++) {
      if (textRunes[i] != standardRunes[i]) return false;
    }
    return true;
  }

  /// Нормализация «корня» — только базовые буквы без диакритик,
  /// ٱ→ا. Пробелы сохраняются (для сравнения «по буквам» в
  /// [_startsWithBismillah]).
  static String _normalizeRoot(String text) {
    return text.runes
        .where((r) => !_isArabicMark(r))
        .map((r) => r == 0x671 ? 0x627 : r)
        .map(String.fromCharCode)
        .join();
  }

  /// Является ли Unicode-кодпоинт арабским диакритическим знаком.
  static bool _isArabicMark(int r) {
    // Огласовки (харакат): U+064B..U+065F
    if (r >= 0x064B && r <= 0x065F) return true;
    // Специфичные знаки
    if (r == 0x0640) return true; // Tatweel
    if (r == 0x0670) return true; // Superscript alef
    if (r == 0x0653) return true; // Maddahan
    if (r == 0x0654) return true; // Hamza above
    if (r == 0x0655) return true; // Hamza below
    if (r == 0x06E1) return true; // Dotless beh
    if (r == 0x06D6 || r == 0x06D7 || r == 0x06D8 || r == 0x06D9) return true; // Quran marks
    return false;
  }
}
